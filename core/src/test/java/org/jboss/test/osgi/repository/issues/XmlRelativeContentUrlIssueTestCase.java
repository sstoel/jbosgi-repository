package org.jboss.test.osgi.repository.issues;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.fail;

import java.io.ByteArrayInputStream;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;

import org.jboss.osgi.repository.RepositoryReader;
import org.jboss.osgi.repository.RepositoryXMLReader;
import org.jboss.osgi.resolver.XResource;
import org.junit.Test;

/**
 * The repository XML reader rejects a relative osgi.content url (the common form in repository indexes) and aborts
 * reading the whole document with "JBOSGI020508: Invalid content URL".
 *
 * <h2>Severity</h2>
 * minor. Standard repository indexes (e.g. generated by bnd, which relativizes content URLs) cannot be read at all.
 *
 * <h2>Component</h2>
 * jbosgi-repository, module core, class org.jboss.osgi.repository.RepositoryXMLReader (readResourceElement); the reader
 * API (create(InputStream)) has no way to receive the document URL.
 *
 * <h2>Found by</h2>
 * subrepos-b workstream, XML format conformance review; bnd 7.0.0 XMLResourceParser as reference.
 *
 * <h2>Spec reference</h2>
 * OSGi Compendium R8 132.5 (https://docs.osgi.org/specification/osgi.cmpn/8.0.0/service.repository.html): "Any relative URIs in a Repository XML file must be resolved as specified in
 * [5] XML Base (Second Edition), Resolving Relative URIs."
 *
 * <h2>Code location</h2>
 * core/src/main/java/org/jboss/osgi/repository/RepositoryXMLReader.java:142-149: new URL(urlspec) for the content url,
 * MalformedURLException -&gt; MESSAGES.invalidContentURL (RepositoryStorageException). Pre-existing.
 *
 * <h2>Root cause</h2>
 * No base URI handling; java.net.URL cannot represent a relative reference without a context.
 *
 * <h2>Reproduction</h2>
 * <pre>
 * cd jbosgi-repository
 * JAVA_HOME=/opt/homebrew/opt/openjdk@25/libexec/openjdk.jdk/Contents/Home mvn -Dmaven.compiler.proc=full install -DskipTests
 * JAVA_HOME=/opt/homebrew/opt/openjdk@25/libexec/openjdk.jdk/Contents/Home mvn -Dmaven.compiler.proc=full -pl core test -Dtest=XmlRelativeContentUrlIssueTestCase
 * </pre>
 *
 * <h2>Observed</h2>
 * <pre>
 * testRelativeContentUrl: Expected the resource with the relative content URL 'bundles/org.acme.pool-1.5.6.jar' to be read
 *   (132.5: relative URIs must be resolved per XML Base), but reading the repository failed with:
 *   org.jboss.osgi.repository.RepositoryStorageException: JBOSGI020508: Invalid content URL: bundles/org.acme.pool-1.5.6.jar
 * </pre>
 *
 * <h2>Expected</h2>
 * The resource is read. Its content url is resolved against the document location (xml:base / the URL it was loaded
 * from) when that is known; otherwise the reference is kept as given and only an access to the content can fail.
 *
 * <h2>Reference behaviour</h2>
 * bnd 7.0.0 XMLResourceParser resolves it to file:/.../bundles/org.acme.pool-1.5.6.jar.
 *
 * <h2>Suggested fix</h2>
 * Add RepositoryXMLReader.create(InputStream, URI base) (and honour xml:base) and resolve content urls with
 * base.resolve(urlspec). Without a base, do not turn the resource into a URLResource eagerly (keep the url attribute as
 * given) instead of aborting the whole document.
 *
 * <h2>Regression vs WF41</h2>
 * no (pre-existing, same code on WF41).
 */
public class XmlRelativeContentUrlIssueTestCase {

    private static final String XML = "<?xml version='1.0' encoding='UTF-8'?>"
            + "<repository xmlns='http://www.osgi.org/xmlns/repository/v1.0.0' name='index'>"
            + "<resource>"
            + "<capability namespace='osgi.identity'>"
            + "<attribute name='osgi.identity' value='org.acme.pool'/>"
            + "<attribute name='version' type='Version' value='1.5.6'/>"
            + "<attribute name='type' value='osgi.bundle'/>"
            + "</capability>"
            + "<capability namespace='osgi.content'>"
            + "<attribute name='osgi.content' value='e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855'/>"
            + "<attribute name='url' value='bundles/org.acme.pool-1.5.6.jar'/>"
            + "<attribute name='size' type='Long' value='4405'/>"
            + "<attribute name='mime' value='application/vnd.osgi.bundle'/>"
            + "</capability>"
            + "</resource>"
            + "</repository>";

    @Test
    public void testRelativeContentUrl() throws Exception {
        RepositoryReader reader = RepositoryXMLReader.create(new ByteArrayInputStream(XML.getBytes(StandardCharsets.UTF_8)));
        List<XResource> resources = new ArrayList<XResource>();
        try {
            XResource res = reader.nextResource();
            while (res != null) {
                resources.add(res);
                res = reader.nextResource();
            }
        } catch (RuntimeException ex) {
            fail("Expected the resource with the relative content URL 'bundles/org.acme.pool-1.5.6.jar' to be read "
                    + "(132.5: relative URIs must be resolved per XML Base), but reading the repository failed with: " + ex);
        } finally {
            reader.close();
        }
        assertEquals(1, resources.size());
    }
}
